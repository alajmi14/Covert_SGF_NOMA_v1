def sheet(name):
    ws = wb.create_sheet(name)
    ws.sheet_view.showGridLines = True
    return ws


def put(ws, r, c, v, font=f_norm, fill=None, fmt=None, comment=None, align=None):
    cell = ws.cell(row=r, column=c, value=v)
    cell.font = font
    if fill: cell.fill = fill
    if fmt: cell.number_format = fmt
    if comment: cell.comment = Comment(comment, "export_results.py")
    if align: cell.alignment = Alignment(horizontal=align)
    return cell


def header(ws, r, labels, c0=1):
    for j, lab in enumerate(labels):
        put(ws, r, c0 + j, lab, f_bold, fill_hdr).border = border
        put(ws, r, c0 + j, lab, f_bold, fill_hdr).alignment = Alignment(wrap_text=True, vertical="top")


def widths(ws, w):
    for i, x in enumerate(w, 1):
        ws.column_dimensions[get_column_letter(i)].width = x


def title(ws, text, sub=None):
    put(ws, 1, 1, text, f_title)
    if sub: put(ws, 2, 1, sub, f_note)


def table(ws, r0, cols, rows, fmts=None, c0=1):
    """cols: header labels; rows: list of row lists (None -> blank).  Returns next free row."""
    header(ws, r0, cols, c0)
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            if v is None: continue
            fmt = (fmts[j] if fmts and j < len(fmts) else None)
            put(ws, r0 + 1 + i, c0 + j, v, f_norm, None, fmt)
    ws.freeze_panes = ws.cell(row=r0 + 1, column=c0)
    return r0 + 1 + len(rows)


